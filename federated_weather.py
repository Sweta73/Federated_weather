"""# Model and loss"""

TAUS = [0.5, 0.8, 0.9, 0.95, 0.99]

class QNet(nn.Module):
    def __init__(self, d_in, h=64, k=len(TAUS)):
        super().__init__()
        self.f = nn.Sequential(nn.Linear(d_in, h), nn.ReLU(), nn.Linear(h, h), nn.ReLU(), nn.Linear(h, k))
    def forward(self, x):
        return torch.sort(self.f(x), dim=1).values          # no quantile crossing

def pinball(pred, y, taus):
    t = torch.tensor(taus).view(1, -1)
    e = y.view(-1, 1) - pred
    return torch.maximum(t * e, (t - 1) * e).mean()

def local_train(model, X, Y, epochs, lr=2e-3, bs=128):
    opt = torch.optim.Adam(model.parameters(), lr=lr)
    X, Y = torch.tensor(X), torch.tensor(Y)
    for _ in range(epochs):
        perm = torch.randperm(len(X))
        for i in range(0, len(X), bs):
            b = perm[i:i + bs]
            opt.zero_grad(); pinball(model(X[b]), Y[b], TAUS).backward(); opt.step()
    return model.state_dict()

"""# federated training (FedAvg)"""

ROUNDS, LOCAL_EPOCHS = 30, 2

def fedavg(clients, rounds=ROUNDS, epochs=LOCAL_EPOCHS):
    d_in = next(iter(clients.values()))["Xtr"].shape[1]
    glob = QNet(d_in)
    for r in range(rounds):
        states, ws = [], []
        for c in clients.values():
            m = QNet(d_in); m.load_state_dict(glob.state_dict())
            states.append(local_train(m, c["Xtr"], c["Ytr"], epochs)); ws.append(len(c["Xtr"]))
        w = np.array(ws, float) / sum(ws)
        glob.load_state_dict({k: sum(wi * s[k] for wi, s in zip(w, states)) for k in states[0]})
        if (r + 1) % 10 == 0: print(f"round {r + 1}/{rounds}")
    return glob

model = fedavg(clients)

"""# Conformal helpers"""

def sketch(scores, m=100):
    if len(scores) == 0: return np.array([]), 0
    return np.quantile(scores, (np.arange(m) + 0.5) / m), len(scores)

def wquantile(sk_list, level):
    vals, wts = [], []
    for s, n in sk_list:
        if n == 0: continue
        vals.append(s); wts.append(np.full(len(s), n / len(s)))
    if not vals: return np.inf
    v, w = np.concatenate(vals), np.concatenate(wts)
    o = np.argsort(v); v, w = v[o], w[o]
    cw = np.cumsum(w) / w.sum()
    return v[min(np.searchsorted(cw, level), len(v) - 1)]

def conf_q(scores, alpha):
    n = len(scores)
    if n == 0: return np.inf
    k = int(np.ceil((n + 1) * (1 - alpha)))
    return np.inf if k > n else np.sort(scores)[k - 1]

def predict_up(model, X, tau_idx):
    with torch.no_grad():
        return model(torch.tensor(X))[:, tau_idx].numpy()

"""# Calibration (local / global / FedTail) and evaluation"""

ALPHA, N0, N_BINS = 0.1, 50, 4
STORE = {}          # keeps per-client test bounds for the advanced plots

def calibrate_and_eval(model, clients, alpha=ALPHA, n0=N0, n_bins=N_BINS):
    STORE.clear()
    tau_idx = TAUS.index(round(1 - alpha, 2))
    up_ca = {k: predict_up(model, c["Xca"], tau_idx) for k, c in clients.items()}
    sc = {k: c["Yca"] - up_ca[k] for k, c in clients.items()}          # one-sided CQR score

    edges = [wquantile([sketch(up_ca[k]) for k in clients], q) for q in np.linspace(0, 1, n_bins + 1)[1:-1]]
    binid = lambda u: np.digitize(u, edges)

    Qg_bin = {}
    for b in range(n_bins):
        sk = [sketch(sc[k][binid(up_ca[k]) == b]) for k in clients]
        Qg_bin[b] = wquantile(sk, 1 - alpha * (1 + 1 / max(sum(s[1] for s in sk), 1)))
    Qg = wquantile([sketch(sc[k]) for k in clients], 1 - alpha)

    res = {m: [] for m in ["uncalibrated", "local", "global", "fedtail"]}
    for k, c in clients.items():
        up = predict_up(model, c["Xte"], tau_idx); y = c["Yte"]
        bins = binid(up)
        Ql = conf_q(sc[k], alpha)
        Q_ft = np.zeros(len(up))
        for b in range(n_bins):
            s_kb = sc[k][binid(up_ca[k]) == b]
            lam = len(s_kb) / (len(s_kb) + n0)
            ql = conf_q(s_kb, alpha) if len(s_kb) else 0.0
            ql = ql if np.isfinite(ql) else Qg_bin[b]
            Q_ft[bins == b] = lam * ql + (1 - lam) * Qg_bin[b]       # shrink local toward pooled-bin threshold
        bounds = {"uncalibrated": up, "local": up + (Ql if np.isfinite(Ql) else 0),
                  "global": up + Qg, "fedtail": up + Q_ft}
        STORE[k] = dict(y=y, up=up, dates=c["Tte"], **bounds)
        tail = y > c["thr"]                       # outcome-defined extremes (diagnostic only)
        top = bins == n_bins - 1                  # covariate-defined high-risk regime (guaranteeable)
        for m, ub in bounds.items():
            cov = y <= ub
            res[m].append(dict(client=k, cov=cov.mean(),
                               risk_cov=cov[top].mean() if top.sum() >= 20 else np.nan,
                               outcome_tail_cov=cov[tail].mean() if tail.sum() else np.nan,
                               n_top=int(top.sum()), n_tail=int(tail.sum()),
                               width=np.mean(ub - up) if m != "uncalibrated" else 0.0))
    return res

res = calibrate_and_eval(model, clients)

