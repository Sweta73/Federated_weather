def make_xy(df, lead=LEAD, win=WIN):
    d = df.copy()
    d["PRECTOTCORR"] = np.log1p(d["PRECTOTCORR"].clip(lower=0))
    for c in PARAMS[1:]:
        d[c] = (d[c] - d[c].mean()) / (d[c].std() + 1e-6)     # local standardisation (no sharing)
    v = d[PARAMS].values.astype(np.float32)
    doy = d.index.dayofyear.values
    X, Y, T = [], [], []
    for t in range(win, len(d) - lead):
        X.append(np.concatenate([v[t - win:t].ravel(),
                                 [np.sin(2 * np.pi * doy[t] / 365), np.cos(2 * np.pi * doy[t] / 365)]]))
        Y.append(v[t + lead, 0]); T.append(d.index[t + lead])
    return np.array(X, np.float32), np.array(Y, np.float32), pd.DatetimeIndex(T)

